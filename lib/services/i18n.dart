import 'package:flutter/widgets.dart';

/// Supported app languages.
///
/// Trackora ships English as the master copy. Chinese (Simplified) and
/// Malay are translated for the most visible UI surfaces — tabs,
/// settings, dashboard chrome, common buttons. Strings that don't have
/// a translation yet **fall through to English** automatically (see
/// [AppStrings.t]) so the app never shows a missing key.
///
/// To add a string: add a key in [AppStrings._en], then translate it in
/// [AppStrings._zh] / [AppStrings._ms]. Look up via `context.t('key')`.
enum AppLocale {
  system,
  en,
  zh,
  ms;

  /// The Flutter [Locale] this maps to. `system` → null, which makes
  /// `MaterialApp` pick from `supportedLocales` based on device.
  Locale? toLocale() {
    switch (this) {
      case AppLocale.system:
        return null;
      case AppLocale.en:
        return const Locale('en');
      case AppLocale.zh:
        return const Locale('zh');
      case AppLocale.ms:
        return const Locale('ms');
    }
  }

  String get label {
    switch (this) {
      case AppLocale.system:
        return 'System default';
      case AppLocale.en:
        return 'English';
      case AppLocale.zh:
        return '中文 (简体)';
      case AppLocale.ms:
        return 'Bahasa Melayu';
    }
  }

  static AppLocale decode(String? raw) {
    switch (raw) {
      case 'en':
        return AppLocale.en;
      case 'zh':
        return AppLocale.zh;
      case 'ms':
        return AppLocale.ms;
      case 'system':
      default:
        return AppLocale.system;
    }
  }

  String encode() {
    switch (this) {
      case AppLocale.system:
        return 'system';
      case AppLocale.en:
        return 'en';
      case AppLocale.zh:
        return 'zh';
      case AppLocale.ms:
        return 'ms';
    }
  }
}

