  String t(String key) {
    final table = switch (languageCode) {
      'zh' => _zh,
      'ms' => _ms,
      _ => _en,
    };
    // Fall back to English for any untranslated key so the app never
    // shows a raw key like "settings.exportCsv".
    return table[key] ?? _en[key] ?? key;
  }
}

/// Convenience: read the active [AppStrings] from a `BuildContext`.
extension StringsLookup on BuildContext {
  String t(String key) {
    final loc = Localizations.maybeLocaleOf(this);
    final code = loc?.languageCode ?? 'en';
    return AppStrings(code).t(key);
  }

  String categoryLabel(String category) {
    final key = 'category.$category';
    final label = t(key);
    // Built-in categories have a translation; custom categories don't, so fall
    // back to their raw name instead of showing the lookup key.
    return label == key ? category : label;
  }

  String appLocaleLabel(AppLocale locale) {
    return switch (locale) {
      AppLocale.system => t('locale.system'),
      AppLocale.en => t('locale.en'),
      AppLocale.zh => t('locale.zh'),
      AppLocale.ms => t('locale.ms'),
    };
  }
}
